--       "where do visitors drop off in the validation funnel" (analyze
--       enqueued / cache hit / report viewed / share clicked). Privacy hard
--       constraints: NO account id, NO IP, NO analyzed username, NO UA string;
--       session stitching uses only the 24h random ja_sid cookie. No foreign
--       key on profile_id (profiles may be deleted while events stay) and no
--       CHECK constraints: value-domain evolution is guarded by application
--       Zod (packages/shared funnel.ts). Timestamps stay TEXT ISO8601 to
--       match the dual-dialect schema convention.

CREATE TABLE IF NOT EXISTS funnel_events (
  -- id: event primary key (fe-<uuid>, generated by the funnel recorder)
  id TEXT PRIMARY KEY,
  -- event: funnel step (analyze_enqueued | analyze_cache_hit | report_viewed | share_clicked)
  event TEXT NOT NULL,
  -- session_ref: anonymous session id from the 24h ja_sid cookie; NULL for non-browser sources
  session_ref TEXT,
  -- profile_id: profile uuid the event relates to; only report_viewed / share_clicked may carry it
  profile_id TEXT,
  -- requester: who triggered (user | demo | visitor); NULL when not applicable
  requester TEXT,
  -- created_at: event time (UTC ISO8601, injected by the recorder)
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP)
);

CREATE INDEX IF NOT EXISTS idx_funnel_events_created
  ON funnel_events (created_at);

CREATE INDEX IF NOT EXISTS idx_funnel_events_session_event_created
  ON funnel_events (session_ref, event, created_at);

CREATE INDEX IF NOT EXISTS idx_funnel_events_event_profile_created
  ON funnel_events (event, profile_id, created_at);

