-- Note: SQLite dialect. Append-only audit log for destructive/ownership events
--       on profiles (first event: 'deleted' before the cascade wipes
--       evidence/applications/interviews). Unlike funnel_events this table
--       deliberately records actor_account_id: audit without an accountable
--       actor is useless for dispute resolution. No foreign key on
--       profile_id (the profile row is deleted right after the event) and no
--       CHECK constraints: event value-domain evolution is guarded by the
--       application layer. Timestamps stay TEXT ISO8601 to match the
--       dual-dialect schema convention.

CREATE TABLE IF NOT EXISTS profile_events (
  -- id: event primary key (pev-<uuid>, generated by the API layer)
  id TEXT PRIMARY KEY,
  -- profile_id: profile uuid the event relates to; no FK (profile may be deleted)
  profile_id TEXT NOT NULL,
  -- event: audit event name (deleted; reserved for future claim/unclaim events)
  event TEXT NOT NULL,
  -- actor_account_id: accounts.id of the operator; NULL for system/operator actions
  actor_account_id TEXT,
  -- detail_json: JSON snapshot with context (subject platform/login, cascade counts)
  detail_json TEXT,
  -- created_at: event time (UTC ISO8601, injected by the caller)
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP)
);

CREATE INDEX IF NOT EXISTS idx_profile_events_profile_created
  ON profile_events (profile_id, created_at);

CREATE INDEX IF NOT EXISTS idx_profile_events_event_created
  ON profile_events (event, created_at);

