-- Note: SQLite dialect. Append-only cost/usage event log. It records RAW UNITS
--       (token counts / call counts), never money: the goal is answering "which
--       feature is burning budget" (builtin LLM tokens, paid Tavily searches,
--       analysis job compute), not pricing. No foreign key on account_id and no
--       CHECK constraints: anonymous/platform-level events carry NULL account_id,
--       and category/feature/billing_source evolution is guarded by application
--       Zod (packages/shared usage.ts). Timestamps stay TEXT ISO8601 to match the
--       dual-dialect schema convention (postgres migration uses TEXT too).

CREATE TABLE IF NOT EXISTS usage_events (
  -- id: event primary key (usg-<uuid>, generated by the usage recorder)
  id TEXT PRIMARY KEY,
  -- account_id: triggering account; NULL for anonymous/platform-level events
  account_id TEXT,
  -- category: cost class (llm | search | analysis)
  category TEXT NOT NULL,
  -- feature: feature point (cover_letter | resume_polish | jd_extraction | semantic_summary | websearch | analysis_job)
  feature TEXT NOT NULL,
  -- billing_source: who pays (builtin=platform-paid builtin LLM | byok=user key | platform=platform infra)
  billing_source TEXT NOT NULL,
  -- provider: provider identifier (LLM provider name | tavily | github | gitee | all); NULL when n/a
  provider TEXT,
  -- model: model identifier for LLM events; NULL when n/a
  model TEXT,
  -- prompt_tokens: input token count; NULL for non-LLM events
  prompt_tokens INTEGER,
  -- completion_tokens: output token count; NULL for non-LLM events
  completion_tokens INTEGER,
  -- quantity: non-token units (Tavily query count, analysis job cost weight 1|2); NULL when n/a
  quantity INTEGER,
  -- created_at: event time (UTC ISO8601, injected by the recorder)
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP)
);

CREATE INDEX IF NOT EXISTS idx_usage_events_created
  ON usage_events (created_at);

CREATE INDEX IF NOT EXISTS idx_usage_events_account_created
  ON usage_events (account_id, created_at);

CREATE INDEX IF NOT EXISTS idx_usage_events_category_created
  ON usage_events (category, created_at);

